CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, pw_hash TEXT NOT NULL, pw_salt TEXT NOT NULL, iter INTEGER NOT NULL,
  rec_hash TEXT NOT NULL, rec_salt TEXT NOT NULL, created INTEGER NOT NULL, ai_day TEXT NOT NULL DEFAULT '', ai_count INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, created INTEGER NOT NULL, last_used INTEGER NOT NULL, expires INTEGER NOT NULL, device TEXT
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions (user_id);
CREATE TABLE IF NOT EXISTS rows (
  user_id TEXT NOT NULL, store TEXT NOT NULL, key TEXT NOT NULL, value TEXT NOT NULL, deleted INTEGER NOT NULL DEFAULT 0, updated INTEGER NOT NULL,
  PRIMARY KEY (user_id, store, key)
);
CREATE INDEX IF NOT EXISTS rows_updated ON rows (user_id, updated);
CREATE TABLE IF NOT EXISTS backups (
  user_id TEXT NOT NULL, day TEXT NOT NULL, store TEXT NOT NULL, data TEXT NOT NULL, created INTEGER NOT NULL, PRIMARY KEY (user_id, day, store)
);
CREATE TABLE IF NOT EXISTS attempts (k TEXT PRIMARY KEY, n INTEGER NOT NULL, t INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS ident (sub TEXT PRIMARY KEY, user_id TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS ident_user ON ident (user_id);
CREATE TABLE IF NOT EXISTS otps (k TEXT PRIMARY KEY, code_hash TEXT NOT NULL, exp INTEGER NOT NULL, tries INTEGER NOT NULL, created INTEGER NOT NULL);
